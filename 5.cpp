int main(){
    int a=4,b=7;
    cout<<"hi hope it works "<<endl;
    // arithmetic operator
    cout<<"the sum of a+b is "<<a+b<<endl;
    cout<<"the sum of a-b is "<<a-b<<endl;
    cout<<"the sum of a*b is "<<a*b<<endl;
    cout<<"the sum of a/b is "<<a/b<<endl;
    cout<<"the sum of a++b is "<<a++<<endl;
    cout<<"the sum of a--b is "<<a--<<endl;
    cout<<endl;

    // comparison operator
    cout<<"the sum of a==b is "<<(a==b)<<endl;
    cout<<"the sum of a!=b is "<<(a!=b)<<endl;
    cout<<"the sum of a>=b is "<<(a>=b)<<endl;
    cout<<"the sum of a<=b is "<<(a<=b)<<endl;
    cout<<"the sum of a>b is "<<(a<b)<<endl;
    cout<<"the sum of a<b is "<<(a>b)<<endl;
    cout<<endl;
    return 0;
     
}
